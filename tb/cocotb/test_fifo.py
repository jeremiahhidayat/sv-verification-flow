@cocotb.test()
async def test_reset(dut):
    """Spec: F1 -- reset clears count and both pointers, from a non-trivial state."""
    tb = await setup(dut)

    # Put something in first, so the reset has state to clear rather than
    # passing trivially from a cold start.
    await tb.fill(DEPTH // 2)
    tb.expect_state("before reset", DEPTH // 2)

    await tb.reset()
    tb.expect_state("after reset", 0)
    if tb.check_ptrs:
        assert tb.last.wr_addr == 0, f"wr_addr_r={tb.last.wr_addr} after reset"
        assert tb.last.rd_addr == 0, f"rd_addr_r={tb.last.rd_addr} after reset"

    # rd_data is deliberately NOT checked here: fifo_spec.md Sec.3 excludes the
    # read pipeline from reset, so asserting rd_data == 0 would be asserting a
    # guarantee the design does not make.
    tb.check_no_errors()


@cocotb.test()
async def test_fill_to_full(dut):
    """Spec: F2, F4, F10 -- writes commit and count reaches DEPTH, then full holds."""
    tb = await setup(dut)

    for i in range(DEPTH):
        snap = await tb.cycle(wr=1)
        assert snap.count == i + 1, f"count={snap.count} after {i + 1} writes"

    tb.expect_state("filled", DEPTH)
    assert tb.last.full == 1

    # F4: further writes while full are dropped and do not advance the pointer.
    wr_addr_at_full = tb.last.wr_addr
    await tb.cycle(wr=1)
    tb.expect_state("write while full", DEPTH)
    if tb.check_ptrs:
        assert tb.last.wr_addr == wr_addr_at_full, "write pointer moved while full"

    tb.check_no_errors()


@cocotb.test()
async def test_drain_to_empty(dut):
    """Spec: F3, F5, F10 -- reads commit in order and count returns to 0."""
    tb = await setup(dut)

    await tb.fill(DEPTH)
    tb.expect_state("filled", DEPTH)

    for i in range(DEPTH):
        snap = await tb.cycle(rd=1)
        assert snap.count == DEPTH - i - 1, f"count={snap.count} after {i + 1} reads"

    tb.expect_state("drained", 0)

    # F5: further reads while empty are dropped.
    rd_addr_at_empty = tb.last.rd_addr
    await tb.cycle(rd=1)
    tb.expect_state("read while empty", 0)
    if tb.check_ptrs:
        assert tb.last.rd_addr == rd_addr_at_empty, "read pointer moved while empty"

    await tb.idle(2)  # let the last read mature so the scoreboard sees it
    tb.check_no_errors()


@cocotb.test()
async def test_pointer_wrap(dut):
    """Spec: F9 -- both pointers wrap mod DEPTH; occupancy stays correct across >=2 wraps."""
    tb = await setup(dut)

    # Half-fill first so the two pointers wrap at different times rather than in
    # lockstep -- a model that tracked only their difference would pass a
    # lockstep test.
    await tb.fill(DEPTH // 2)

    for _ in range(2 * DEPTH + DEPTH // 2):
        await tb.cycle(wr=1, rd=1)

    await tb.drain(DEPTH // 2)
    await tb.idle(2)

    assert tb.model.wr_wraps >= 2, f"write pointer wrapped {tb.model.wr_wraps} times, need >= 2"
    assert tb.model.rd_wraps >= 2, f"read pointer wrapped {tb.model.rd_wraps} times, need >= 2"
    tb.expect_state("after wraps", 0)
    tb.check_no_errors()


@cocotb.test()
async def test_simultaneous_rw_mid(dut):
    """Spec: F6 -- wr+rd while neither full nor empty: both commit, count unchanged."""
    tb = await setup(dut)

    await tb.fill(DEPTH // 2)
    tb.expect_state("half full", DEPTH // 2)

    for _ in range(DEPTH):
        snap = await tb.cycle(wr=1, rd=1)
        assert snap.count == DEPTH // 2, f"count={snap.count}, expected {DEPTH // 2} (F6)"

    await tb.drain(DEPTH // 2)
    await tb.idle(2)
    tb.check_no_errors()


@cocotb.test()
async def test_simultaneous_rw_at_full(dut):
    """Spec: F7 -- wr+rd while full: the read commits, the write is dropped.

    This is the case that caught the spec/RTL mismatch recorded in
    verification_plan.md Sec.4, and it caught it only because it is directed.
    The per-cycle count comparison stayed silent (the Questa model had inherited
    `wr_en && !full` from the RTL) and `a_no_overflow` is qualified on `!rd_en`
    so it never evaluated here. Occupancy settling at DEPTH-1 rather than DEPTH
    is the observable consequence.
    """
    tb = await setup(dut)

    await tb.fill(DEPTH)
    tb.expect_state("full", DEPTH)

    # First simultaneous cycle at full: the write is dropped, so the slot the
    # read frees is not refilled.
    snap = await tb.cycle(wr=1, rd=1)
    assert snap.count == DEPTH - 1, f"count={snap.count}, expected {DEPTH - 1} (F7)"

    # Sustained: no longer full, so both commit every cycle and occupancy sits
    # at DEPTH-1. One slot of effective depth, no throughput loss, no data loss.
    for _ in range(DEPTH):
        snap = await tb.cycle(wr=1, rd=1)
        assert snap.count == DEPTH - 1, f"count={snap.count}, expected {DEPTH - 1} under sustained rw"

    await tb.drain(DEPTH - 1)
    await tb.idle(2)
    tb.expect_state("drained", 0)
    tb.check_no_errors()


@cocotb.test()
async def test_simultaneous_rw_at_empty(dut):
    """Spec: F8 -- wr+rd while empty: the write commits, the read is dropped."""
    tb = await setup(dut)
    tb.expect_state("empty", 0)

    snap = await tb.cycle(wr=1, rd=1)
    assert snap.count == 1, f"count={snap.count}, expected 1 (F8)"

    # And the word that went in is the one that comes back out -- proof the
    # dropped read did not consume it.
    await tb.cycle(rd=1)
    await tb.idle(2)
    tb.expect_state("drained", 0)
    tb.check_no_errors()


@cocotb.test()
async def test_write_while_full_no_read(dut):
    """Spec: F4, F11 -- sustained writes while full corrupt nothing already stored."""
    tb = await setup(dut)

    await tb.fill(DEPTH)
    tb.expect_state("full", DEPTH)
    wr_addr_at_full = tb.last.wr_addr

    for _ in range(DEPTH):
        snap = await tb.cycle(wr=1)
        assert snap.count == DEPTH, f"count={snap.count} under sustained back-pressure (F11)"
        if tb.check_ptrs:
            assert snap.wr_addr == wr_addr_at_full, "write pointer moved while full"

    # Reading it all back is what actually proves the stored data survived: the
    # scoreboard compares every word against the model's queue, which never
    # accepted any of the dropped writes.
    await tb.drain(DEPTH)
    await tb.idle(2)
    tb.expect_state("drained", 0)
    assert tb.data_checks >= DEPTH, f"only {tb.data_checks} rd_data checks, expected >= {DEPTH}"
    tb.check_no_errors()


@cocotb.test()
async def test_read_while_empty_no_write(dut):
    """Spec: F5, F12 -- sustained reads while empty return no data and move nothing."""
    tb = await setup(dut)
    tb.expect_state("empty", 0)

    rd_addr_at_empty = tb.last.rd_addr
    held = tb.last.rd_data
    for _ in range(DEPTH):
        snap = await tb.cycle(rd=1)
        assert snap.count == 0, f"count={snap.count} under sustained underflow (F12)"
        assert snap.empty == 1
        if tb.check_ptrs:
            assert snap.rd_addr == rd_addr_at_empty, "read pointer moved while empty"
        # F12: rd_data holds its previous value; no data enters the pipeline.
        assert snap.rd_data == held, f"rd_data changed to 0x{snap.rd_data:x} while empty"

    tb.check_no_errors()


@cocotb.test()
async def test_reset_mid_burst(dut):
    """Spec: F15 -- reset with entries stored and a read in flight clears pointers and count."""
    tb = await setup(dut)

    await tb.fill(DEPTH // 2)
    await tb.cycle(rd=1)  # a word is now in flight in the read pipeline
    assert tb.last.count == DEPTH // 2 - 1

    await tb.reset()
    tb.expect_state("after mid-burst reset", 0)
    if tb.check_ptrs:
        assert tb.last.wr_addr == 0, f"wr_addr_r={tb.last.wr_addr} after mid-burst reset"
        assert tb.last.rd_addr == 0, f"rd_addr_r={tb.last.rd_addr} after mid-burst reset"

    # Whatever was in flight is left as-is by design (fifo_spec.md Sec.3), so
    # the real proof that reset worked is that the FIFO behaves from scratch
    # afterwards -- including returning the first post-reset word, not a
    # leftover one.
    await tb.cycle(wr=1, data=0xA5 & DATA_MASK)
    await tb.cycle(rd=1)
    await tb.idle(2)
    tb.expect_state("post-reset traffic", 0)
    tb.check_no_errors()


@cocotb.test()
async def test_back_to_back_reads(dut):
    """Spec: F13 -- one read accepted per cycle despite the 2-stage read pipeline."""
    tb = await setup(dut)

    await tb.fill(DEPTH)
    tb.expect_state("full", DEPTH)

    reads_before = tb.model.accepted_reads
    checks_before = tb.data_checks

    for i in range(DEPTH):
        snap = await tb.cycle(rd=1)
        # No throughput loss: exactly one entry leaves per cycle. A design that
        # stalled for the extra pipeline stage would decrement every other cycle.
        assert snap.count == DEPTH - i - 1, (
            f"count={snap.count} on back-to-back read {i}, expected {DEPTH - i - 1}"
        )

    assert tb.model.accepted_reads - reads_before == DEPTH, "not one accepted read per cycle"

    await tb.idle(2)  # flush the pipeline so the last words get compared
    # Every one of those reads was checked for value and for arrival cycle by
    # the per-cycle scoreboard; this asserts none of them silently went missing.
    assert tb.data_checks - checks_before == DEPTH, (
        f"{tb.data_checks - checks_before} rd_data checks for {DEPTH} reads"
    )
    tb.check_no_errors()


@cocotb.test()
async def test_read_pipeline_bubble(dut):
    """Spec: F16 -- rd_data never shows a bubble on cycles with no accepted read.

    Covers both ways a read fails to be accepted: rd_en deasserted, and rd_en
    asserted while empty (F5/F8). The continuous check in Fifo._check_no_bubble
    is running underneath this the whole time; the directed sequence below is
    what guarantees the interesting windows actually occur.
    """
    tb = await setup(dut)

    # Case 1: rd_en deasserted, FIFO non-empty.
    await tb.fill(DEPTH // 2)
    await tb.cycle(rd=1)  # accepted read at this edge

    values = []
    for _ in range(6):
        values.append((await tb.cycle()).rd_data)
    # values[0] is the read's own data arriving one edge after acceptance; from
    # there the read address is parked, so everything after it must be identical.
    assert len(set(values[1:])) == 1, f"rd_data not held with no accepted read: {[hex(v) for v in values]}"

    # Case 2: rd_en asserted but dropped because the FIFO is empty.
    await tb.drain(DEPTH // 2 - 1)
    await tb.idle(3)
    tb.expect_state("empty", 0)

    held = tb.last.rd_data
    for _ in range(6):
        snap = await tb.cycle(rd=1)
        assert snap.rd_data == held, f"rd_data changed to 0x{snap.rd_data:x} on a dropped read"

    tb.check_no_errors()


@cocotb.test()
async def test_almost_full_threshold(dut):
    """Spec: F10 -- almost_full is exact match: it asserts at the threshold and
    deasserts again above it.

    Walks occupancy one entry at a time from 0 to DEPTH and back, recording the
    flag at every occupancy, then asserts the set of occupancies where it was
    high is exactly {ALMOST_FULL_THRESHOLD}. Checking only that it asserts *at*
    the threshold would pass for a `>=` flag too; the deassertion above it is
    the whole difference.
    """
    tb = await setup(dut)

    if ALMOST_FULL_THRESHOLD == DEPTH:
        log.info(
            "NOTE: ALMOST_FULL_THRESHOLD == DEPTH, so exact-match and "
            "threshold-and-above almost_full are indistinguishable in this "
            "elaboration. `make sweep` runs THRESHOLD=1 and DEPTH/2 as well; "
            "F10 is not closed by this run alone (verification_plan.md Sec.4)."
        )

    seen: dict[int, int] = {}

    await tb.idle(1)
    seen[0] = tb.last.almost_full

    for _ in range(DEPTH):  # walk up
        snap = await tb.cycle(wr=1)
        seen[tb.model.occupancy] = snap.almost_full

    for _ in range(DEPTH):  # walk back down
        snap = await tb.cycle(rd=1)
        occ = tb.model.occupancy
        # Only record if the walk up did not already disagree -- it must not.
        if occ in seen and seen[occ] != snap.almost_full:
            tb._fail(f"almost_full={snap.almost_full} at occupancy {occ} on the way down, "
                     f"but {seen[occ]} on the way up")
        seen[occ] = snap.almost_full

    missing = [occ for occ in range(DEPTH + 1) if occ not in seen]
    assert not missing, f"occupancies never visited by the walk: {missing}"

    high = sorted(occ for occ, flag in seen.items() if flag)
    assert high == [ALMOST_FULL_THRESHOLD], (
        f"almost_full was high at occupancies {high}, expected exactly "
        f"[{ALMOST_FULL_THRESHOLD}] -- an exact-match flag, not >= (F10)"
    )

    await tb.idle(2)
    tb.check_no_errors()


@cocotb.test()
async def test_random_stress(dut):
    """Spec: F11, F12, F14 -- randomized traffic against the reference model.

    Weights sweep across the run -- write-heavy, then balanced, then read-heavy
    -- so the FIFO actually sits at full and at empty under sustained pressure.
    A single balanced distribution spends nearly all its time mid-occupancy and
    reaches neither extreme reliably.
    """
    tb = await setup(dut)
    log.info("random stress: %d transactions, seed=%d (rerun with FIFO_SEED=%d)", NUM_TESTS, SEED, SEED)

    for i in range(NUM_TESTS):
        if i < NUM_TESTS // 3:
            wr_weight, rd_weight = 85, 30  # toward full  -> F11
        elif i < (2 * NUM_TESTS) // 3:
            wr_weight, rd_weight = 55, 55  # balanced     -> F6/F9/F14
        else:
            wr_weight, rd_weight = 25, 85  # toward empty -> F12

        wr = int(tb.rnd.randrange(100) < wr_weight)
        rd = int(tb.rnd.randrange(100) < rd_weight)
        await tb.cycle(wr=wr, rd=rd)

        # Back-to-back traffic is what stresses a FIFO, so gaps stay rare.
        if tb.rnd.randrange(100) < 20:
            await tb.idle(tb.rnd.randint(1, 9))

    # Drain whatever is left so the trailing words get their ordering checked.
    await tb.drain(DEPTH)
    await tb.idle(3)
    tb.expect_state("drained", 0)

    m = tb.model
    log.info(
        "accepted writes=%d reads=%d | rd_data checks=%d | wraps wr=%d rd=%d",
        m.accepted_writes,
        m.accepted_reads,
        tb.data_checks,
        m.wr_wraps,
        m.rd_wraps,
    )
    # A stress run that never reached the extremes proves much less than it
    # looks like it does, so say so rather than passing quietly.
    assert m.wr_wraps >= 2 and m.rd_wraps >= 2, (
        f"stress run wrapped only wr={m.wr_wraps} rd={m.rd_wraps} times (F9 wants >= 2); "
        "raise FIFO_NUM_TESTS or lower FIFO_DEPTH"
    )
    assert tb.data_checks > 0
    tb.check_no_errors()
